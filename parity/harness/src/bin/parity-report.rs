//! parity-report: writes parity/report/latest.md from the catalogue and the
//! per-suite results the harness tests left in parity/report/results/.
//!
//!   parity-report             write latest.md (exit 1 on ratchet violations)
//!   parity-report --baseline  also freeze latest as baseline.{json,md}
//!   parity-report targets     print "<crate> <test-binary>" pairs to run
//!   parity-report validate    print catalogue errors (exit 1 if any)

use scryer_parity::{AREAS, CaseResult, Catalogue, Status, parity_dir, parse_test};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

fn main() {
    let arg = std::env::args().nth(1);
    let catalogue = Catalogue::load();
    if arg.as_deref() == Some("targets") {
        let pairs: BTreeSet<(String, String)> = catalogue
            .entries
            .iter()
            .flat_map(|(_, e)| e.tests.iter())
            .filter_map(|t| parse_test(t).map(|(c, b, _)| (c.to_string(), b.to_string())))
            .collect();
        for (c, b) in pairs {
            println!("{c} {b}");
        }
        return;
    }

    let errors = catalogue.validate();
    if arg.as_deref() == Some("validate") {
        for e in &errors {
            println!("{e}");
        }
        println!("{} entries, {} errors", catalogue.entries.len(), errors.len());
        std::process::exit(i32::from(!errors.is_empty()));
    }
    let report = parity_dir().join("report");
    let mut results: BTreeMap<String, CaseResult> = BTreeMap::new();
    let mut suites_run = BTreeSet::new();
    if let Ok(dir) = std::fs::read_dir(report.join("results")) {
        for f in dir.flatten() {
            suites_run.insert(f.file_name().to_string_lossy().trim_end_matches(".json").replace("__", "::"));
            let list: Vec<CaseResult> = serde_json::from_str(&std::fs::read_to_string(f.path()).unwrap()).unwrap();
            for r in list {
                results.insert(r.id.clone(), r);
            }
        }
    }
    let status: BTreeMap<String, Status> =
        catalogue.entries.iter().map(|(_, e)| (e.id.clone(), e.status)).collect();
    let baseline: BTreeMap<String, Status> = std::fs::read_to_string(report.join("baseline.json"))
        .ok()
        .map(|t| serde_json::from_str(&t).unwrap())
        .unwrap_or_default();

    let mut md = String::from("# Parity report\n\nGenerated by `parity/run.sh`. Status is the catalogue's; the harness\nfails if an outcome disagrees with it (ratchet).\n\n");
    md.push_str("| Area | Green | Red | Waived | Unmapped | Out of scope | Total |\n|---|---|---|---|---|---|---|\n");
    let mut totals = [0usize; 6];
    for area in AREAS {
        let mut c = [0usize; 6];
        for (_, e) in catalogue.entries.iter().filter(|(a, _)| a == area) {
            let i = match e.status {
                Status::Green => 0,
                Status::Red => 1,
                Status::Waived => 2,
                Status::Unmapped => 3,
            };
            c[i] += 1;
            c[4] += usize::from(!e.in_scope);
            c[5] += 1;
        }
        if c[5] > 0 {
            let _ = writeln!(md, "| {area} | {} | {} | {} | {} | {} | {} |", c[0], c[1], c[2], c[3], c[4], c[5]);
        }
        for i in 0..6 {
            totals[i] += c[i];
        }
    }
    let _ = writeln!(md, "| **all** | {} | {} | {} | {} | {} | {} |\n", totals[0], totals[1], totals[2], totals[3], totals[4], totals[5]);

    let violations: Vec<&CaseResult> = results.values().filter(|r| r.violation.is_some()).collect();
    let expected_suites: BTreeSet<String> =
        catalogue.entries.iter().flat_map(|(_, e)| e.tests.iter().cloned()).collect();
    let not_run: Vec<&String> = expected_suites.difference(&suites_run).collect();
    let _ = writeln!(md, "## Run\n\nSuites run: {} of {}. Cases recorded: {}. Ratchet violations: {}. Catalogue errors: {}.\n",
        expected_suites.len() - not_run.len(), expected_suites.len(), results.len(), violations.len(), errors.len());
    for s in &not_run {
        let _ = writeln!(md, "- not run: `{s}`");
    }
    for r in &violations {
        let _ = writeln!(md, "- violation: {} ({:?}): {}", r.id, r.status, r.violation.as_deref().unwrap_or(""));
    }
    for e in &errors {
        let _ = writeln!(md, "- catalogue: {e}");
    }

    md.push_str("\n## Moved since baseline\n\n");
    if baseline.is_empty() {
        md.push_str("No baseline yet.\n");
    } else {
        let mut moved = 0;
        for (id, s) in &status {
            match baseline.get(id) {
                Some(b) if b != s => {
                    moved += 1;
                    let _ = writeln!(md, "- {id}: {b:?} → {s:?}");
                }
                None => moved += 1,
                _ => {}
            }
        }
        let added = status.keys().filter(|id| !baseline.contains_key(*id)).count();
        let removed: Vec<&String> = baseline.keys().filter(|id| !status.contains_key(*id)).collect();
        for id in &removed {
            let _ = writeln!(md, "- {id}: removed from the catalogue");
        }
        let _ = writeln!(md, "\n{} changed status, {added} added, {} removed.", moved - added, removed.len());
    }

    std::fs::create_dir_all(&report).unwrap();
    std::fs::write(report.join("latest.md"), &md).unwrap();
    if arg.as_deref() == Some("--baseline") {
        std::fs::write(report.join("baseline.json"), serde_json::to_string_pretty(&status).unwrap()).unwrap();
        std::fs::write(report.join("baseline.md"), &md).unwrap();
    }
    print!("{md}");
    if !violations.is_empty() || !errors.is_empty() || !not_run.is_empty() {
        std::process::exit(1);
    }
}
